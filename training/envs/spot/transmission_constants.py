_KNEE_ANGLE = jnp.array(KNEE_TRANSMISSION_TABLE['knee_angle'])
_KNEE_MAX_TORQUE = jnp.array(KNEE_TRANSMISSION_TABLE['max_output_torque'])


def knee_max_torque(knee_angle: jax.Array) -> jax.Array:
    """Interpolates the knee's maximum output torque at a given joint angle.

    Linearly interpolates over KNEE_TRANSMISSION_TABLE (101 points, dense
    enough that piecewise-linear reproduces Boston Dynamics' published curve
    exactly at every sampled angle). Angles outside the table's range are
    clamped to the nearest endpoint value.

    Args:
        knee_angle: Knee joint angle [rad].

    Returns:
        Maximum output torque the knee can deliver at that angle [N*m].
    """
    return jnp.interp(knee_angle, _KNEE_ANGLE, _KNEE_MAX_TORQUE)


